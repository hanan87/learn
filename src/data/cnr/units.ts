function build(c: CnrItem): LearningItem {
  return {
    id: c.id,
    polish: c.text,
    syllablesPolish: c.syl,
    hebrew: c.he,
    english: c.en,
    phoneticHebrew: renderNotation(c.syl, 'he'),
    phoneticEnglish: renderNotation(c.syl, 'en'),
    articulationTip: c.tipHe,
    articulationTipEn: c.tipEn,
    backchainingSteps: c.steps ?? autoBackchain(c.text),
    formality: c.formality,
    culturalNote: c.noteHe,
    culturalNoteEn: c.noteEn,
  };
}

