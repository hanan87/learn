/** File name of a picture: "Hot beverage" → "hot-beverage". */
export const pictureSlug = (name: string) =>
  name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

/** The picture of an item, if it has one. */
export const pictureOf = (itemId: string): string | undefined => PICTURES[itemId];

/** Where a picture is served. */
export const pictureUrl = (name: string) => `${import.meta.env.BASE_URL}pictures/${pictureSlug(name)}.webp`;
